//! Rust binding generation (`bridgekit gen-rs`).
//!
//! Emits the `extern "C"` block with the header's signatures exactly
//! (edition-2021 style, matching the family crates), one
//! `#[repr(C)]` opaque struct per handle type, and a small safe
//! wrapper per string-returning function: `<name>_string` calls the
//! raw function, copies the result into an owned `String`, and — for
//! caller-owned `char *` results only — frees the original through
//! the kit's own `<prefix>_free_string`. Borrowed `const char *`
//! results (`<prefix>_version`, `<prefix>_last_error`) are copied and
//! never freed.

use crate::header::{CType, Function, Header};

/// Generate the Rust file text for a parsed header.
///
/// `header_name` is the header's file name (shown in the banner).
///
/// # Errors
/// If a function returns a caller-owned `char *` but the header
/// declares no `<prefix>_free_string`, no safe wrapper can exist —
/// that is a hard error, not a silently unsafe wrapper.
pub fn generate(header: &Header, header_name: &str) -> Result<String, String> {
    let owned = header
        .functions
        .iter()
        .filter(|f| f.ret == CType::CharPtr)
        .count();
    let free_fn = header.free_string_fn();
    if owned > 0 && free_fn.is_none() {
        return Err(format!(
            "header declares {} caller-owned char* result(s) but no <prefix>_free_string to free them with — cannot generate safe wrappers",
            owned
        ));
    }

    let mut out = String::new();
    out.push_str(&format!(
        "// Generated by BridgeKit from {} - do not edit by hand.\n",
        header_name
    ));
    out.push_str("// Regenerate from the kit's shipped header; signatures are\n");
    out.push_str("// copied exactly, never retyped.\n\n");

    // Imports: only what the signatures actually use.
    let mut raw: Vec<&str> = Vec::new();
    let mut uses = |ty: &CType| {
        let name = match ty {
            CType::ConstCharPtr | CType::CharPtr | CType::CharPtrPtr => Some("c_char"),
            CType::Int => Some("c_int"),
            CType::UInt => Some("c_uint"),
            CType::VoidPtr | CType::ConstVoidPtr => Some("c_void"),
            _ => None,
        };
        if let Some(n) = name {
            if !raw.contains(&n) {
                raw.push(n);
            }
        }
    };
    for f in &header.functions {
        uses(&f.ret);
        for p in &f.params {
            uses(&p.ty);
        }
    }
    raw.sort_unstable();
    let has_wrappers = header.functions.iter().any(|f| f.ret.is_string_return());
    if has_wrappers {
        out.push_str("use std::ffi::CStr;\n");
    }
    if !raw.is_empty() {
        out.push_str(&format!("use std::os::raw::{{{}}};\n", raw.join(", ")));
    }
    if has_wrappers || !raw.is_empty() {
        out.push('\n');
    }

    for name in header.handle_types() {
        out.push_str("#[repr(C)]\n");
        out.push_str(&format!(
            "pub struct {} {{\n    _private: [u8; 0],\n}}\n\n",
            name
        ));
    }

    out.push_str("extern \"C\" {\n");
    for f in &header.functions {
        out.push_str(&format!("    pub fn {}({})", f.name, rs_params(f)));
        if f.ret != CType::Void {
            out.push_str(&format!(" -> {}", rs_type(&f.ret)));
        }
        out.push_str(";\n");
    }
    out.push_str("}\n");

    let string_fns: Vec<&Function> = header
        .functions
        .iter()
        .filter(|f| f.ret.is_string_return())
        .collect();
    if !string_fns.is_empty() {
        out.push_str("\n// ----- Safe string wrappers -----\n");
        for f in string_fns {
            out.push_str(&wrapper(f, free_fn));
        }
    }
    Ok(out)
}

/// The `<name>_string` wrapper for one string-returning function.
fn wrapper(f: &Function, free_fn: Option<&str>) -> String {
    let owned = f.ret == CType::CharPtr;
    let call_args = f
        .params
        .iter()
        .map(|p| p.name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    let mut s = String::new();
    s.push('\n');
    if owned {
        s.push_str(&format!(
            "/// Caller-owned result of `{}`: copied into a String, then\n/// freed with `{}`.\n",
            f.name,
            free_fn.unwrap_or("<prefix>_free_string")
        ));
    } else {
        s.push_str(&format!(
            "/// Borrowed result of `{}`: copied into a String, never freed.\n",
            f.name
        ));
    }
    s.push_str(&format!(
        "pub unsafe fn {}_string({}) -> Option<String> {{\n",
        f.name,
        rs_params(f)
    ));
    s.push_str(&format!("    let ptr = {}({});\n", f.name, call_args));
    s.push_str("    if ptr.is_null() {\n        return None;\n    }\n");
    if owned {
        s.push_str("    let out = CStr::from_ptr(ptr).to_string_lossy().into_owned();\n");
        s.push_str(&format!(
            "    {}(ptr);\n    Some(out)\n",
            free_fn.unwrap_or("<prefix>_free_string")
        ));
    } else {
        s.push_str("    Some(CStr::from_ptr(ptr).to_string_lossy().into_owned())\n");
    }
    s.push_str("}\n");
    s
}

fn rs_type(ty: &CType) -> String {
    match ty {
        CType::Void => "()".to_string(),
        CType::Int => "c_int".to_string(),
        CType::UInt => "c_uint".to_string(),
        CType::U32 => "u32".to_string(),
        CType::U64 => "u64".to_string(),
        CType::ConstCharPtr => "*const c_char".to_string(),
        CType::CharPtr => "*mut c_char".to_string(),
        CType::CharPtrPtr => "*mut *mut c_char".to_string(),
        CType::VoidPtr => "*mut c_void".to_string(),
        CType::ConstVoidPtr => "*const c_void".to_string(),
        CType::HandlePtr(n) => format!("*mut {}", n),
        CType::HandlePtrPtr(n) => format!("*mut *mut {}", n),
    }
}

fn rs_params(f: &Function) -> String {
    f.params
        .iter()
        .map(|p| format!("{}: {}", p.name, rs_type(&p.ty)))
        .collect::<Vec<_>>()
        .join(", ")
}
