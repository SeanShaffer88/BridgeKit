//! C# binding generation (`bridgekit gen-cs`).
//!
//! Emits one `public static partial class` whose `[DllImport]` methods
//! carry the header's signatures exactly: `const char *` parameters
//! marshal as `string`, every pointer/handle/out-pointer is `IntPtr`
//! (out-pointers as `out IntPtr`), and string *returns* stay `IntPtr`
//! on the raw import — an owned `char *` misdeclared as `string`
//! would be freed by the CLR with the wrong allocator. Each
//! string-returning function additionally gets a `<name>_string`
//! wrapper that copies the UTF-8 text with
//! `Marshal.PtrToStringUTF8` and, for caller-owned `char *` results,
//! frees the original through the kit's own `<prefix>_free_string`.
//! Borrowed `const char *` results (`<prefix>_version`,
//! `<prefix>_last_error`) are copied and never freed.
//!
//! The class is `public` without exception: a non-public class with
//! `[DllImport]` members compiles fine and then fails at test time
//! with inaccessible-member errors — that exact false-failure cost a
//! smoke-test round in this collection's history.

use crate::header::{CType, Function, Header};

/// Generate the C# file text for a parsed header.
///
/// `header_name` is the header's file name (shown in the banner);
/// `dll_name` is the DLL file name the imports bind to, and the class
/// name is derived from it (`notify_kit.dll` -> `NotifyKit`).
///
/// # Errors
/// If a function returns a caller-owned `char *` but the header
/// declares no `<prefix>_free_string`, no safe wrapper can exist —
/// that is a hard error, not a silently unsafe wrapper.
pub fn generate(header: &Header, header_name: &str, dll_name: &str) -> Result<String, String> {
    let owned = header
        .functions
        .iter()
        .filter(|f| f.ret == CType::CharPtr)
        .count();
    let free_fn = header.free_string_fn();
    if owned > 0 && free_fn.is_none() {
        return Err(format!(
            "header declares {} caller-owned char* result(s) but no <prefix>_free_string to free them with — cannot generate safe wrappers",
            owned
        ));
    }

    let class = class_name(dll_name);
    let mut out = String::new();
    out.push_str("// <auto-generated>\n");
    out.push_str(&format!(
        "//   Generated by BridgeKit from {} - do not edit by hand.\n",
        header_name
    ));
    out.push_str("//   Regenerate from the kit's shipped header; signatures are\n");
    out.push_str("//   copied exactly, never retyped.\n");
    out.push_str("// </auto-generated>\n\n");
    out.push_str("using System;\n");
    out.push_str("using System.Runtime.InteropServices;\n\n");
    out.push_str("namespace BridgeKit.Generated\n{\n");
    out.push_str(&format!(
        "    public static partial class {}\n    {{\n",
        class
    ));
    out.push_str(&format!(
        "        private const string DllName = \"{}\";\n",
        dll_name
    ));

    for f in &header.functions {
        out.push('\n');
        out.push_str("        [DllImport(DllName, CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]\n");
        out.push_str(&format!(
            "        public static extern {} {}({});\n",
            cs_return(&f.ret),
            f.name,
            cs_params(f)
        ));
    }

    let string_fns: Vec<&Function> = header
        .functions
        .iter()
        .filter(|f| f.ret.is_string_return())
        .collect();
    if !string_fns.is_empty() {
        out.push_str("\n        // ----- Safe string wrappers -----\n");
        for f in string_fns {
            out.push_str(&wrapper(f, free_fn));
        }
    }

    out.push_str("    }\n}\n");
    Ok(out)
}

/// The `<name>_string` wrapper for one string-returning function.
fn wrapper(f: &Function, free_fn: Option<&str>) -> String {
    let owned = f.ret == CType::CharPtr;
    let call_args = f
        .params
        .iter()
        .map(|p| {
            if matches!(p.ty, CType::CharPtrPtr | CType::HandlePtrPtr(_)) {
                format!("out {}", p.name)
            } else {
                p.name.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    let mut s = String::new();
    s.push('\n');
    if owned {
        s.push_str(&format!(
            "        // Caller-owned string: copied, then freed with {}.\n",
            free_fn.unwrap_or("<prefix>_free_string")
        ));
    } else {
        s.push_str("        // Borrowed string: copied, never freed (the kit owns it).\n");
    }
    s.push_str(&format!(
        "        public static string {}_string({})\n        {{\n",
        f.name,
        cs_params(f)
    ));
    s.push_str(&format!(
        "            IntPtr ptr = {}({});\n",
        f.name, call_args
    ));
    s.push_str("            if (ptr == IntPtr.Zero)\n            {\n                return null;\n            }\n");
    if owned {
        s.push_str("            try\n            {\n");
        s.push_str("                return Marshal.PtrToStringUTF8(ptr);\n");
        s.push_str("            }\n            finally\n            {\n");
        s.push_str(&format!(
            "                {}(ptr);\n",
            free_fn.unwrap_or("<prefix>_free_string")
        ));
        s.push_str("            }\n");
    } else {
        s.push_str("            return Marshal.PtrToStringUTF8(ptr);\n");
    }
    s.push_str("        }\n");
    s
}

fn cs_return(ty: &CType) -> &'static str {
    match ty {
        CType::Void => "void",
        CType::Int => "int",
        CType::UInt | CType::U32 => "uint",
        CType::U64 => "ulong",
        // All pointer returns stay IntPtr on the raw import; the
        // _string wrappers provide the string view.
        _ => "IntPtr",
    }
}

fn cs_param(ty: &CType) -> String {
    match ty {
        CType::Void => "void".to_string(),
        CType::Int => "int".to_string(),
        CType::UInt | CType::U32 => "uint".to_string(),
        CType::U64 => "ulong".to_string(),
        CType::ConstCharPtr => "string".to_string(),
        CType::CharPtrPtr | CType::HandlePtrPtr(_) => "out IntPtr".to_string(),
        _ => "IntPtr".to_string(),
    }
}

fn cs_params(f: &Function) -> String {
    f.params
        .iter()
        .map(|p| format!("{} {}", cs_param(&p.ty), p.name))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `notify_kit.dll` -> `NotifyKit`; `watchkit.dll` -> `Watchkit`.
/// Split on non-alphanumerics, capitalize each part, join.
pub fn class_name(dll_name: &str) -> String {
    let stem = dll_name.strip_suffix(".dll").unwrap_or(dll_name);
    let mut out = String::new();
    for part in stem.split(|c: char| !c.is_ascii_alphanumeric()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            for c in chars {
                out.push(c.to_ascii_lowercase());
            }
        }
    }
    if out.is_empty() {
        out.push_str("Kit");
    }
    out
}
